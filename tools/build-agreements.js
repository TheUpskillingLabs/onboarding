#!/usr/bin/env node
/* build-agreements.js — zero-dep converter (the agreements twin of generate.js).
   Reads the three legal documents in docs/agreements/*.md (pandoc-flavored
   markdown exported from the .docx originals) and emits agreements.js at the
   repo root: window.AGREEMENTS = { participation, guidelines, mentor }, each
   { title, version, html }. The html renders inside the flow engine's
   .agree-scroll box (scroll-gated). Rerun after editing any source doc:

     node tools/build-agreements.js

   Version strings live HERE — bump them when a document's substance changes;
   each acceptance is recorded as {doc, version, at} on the member.        */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'docs', 'agreements');

const DOCS = [
  { key: 'participation', file: 'The_Upskilling_Labs_Volunteer_Participant_Agreement.md',
    title: 'The Volunteer Participation Agreement', version: 'vpa-2026-07-v1' },
  { key: 'guidelines', file: 'The_Upskilling_Labs_Volunteer_Guidelines.md',
    title: 'The Volunteer Guidelines', version: 'vg-2026-07-v1' },
  { key: 'mentor', file: 'Volunteer Mentor Agreement.md',
    title: 'The Volunteer Mentor Agreement', version: 'vma-2026-07-v1' },
];

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function inline(s) {
  return esc(s)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>')
    .replace(/---/g, '—');
}

function mdToHtml(md) {
  // Undo pandoc escapes, normalize newlines, drop blockquote continuation markers.
  md = md.replace(/\r\n/g, '\n').replace(/\\([\'"“”‘’&#$%~_^\[\]()<>])/g, '$1');
  const lines = md.split('\n');
  const out = []; let para = []; let list = null;
  const flushPara = () => { if (para.length) { out.push('<p class="t-small">' + inline(para.join(' ').trim()) + '</p>'); para = []; } };
  const flushList = () => { if (list) { out.push('<ul class="agree-ul">' + list.map(li => '<li class="t-small">' + inline(li.trim()) + '</li>').join('') + '</ul>'); list = null; } };
  for (let i = 0; i < lines.length; i++) {
    let ln = lines[i];
    const next = lines[i + 1] || '';
    // setext headings:  Title \n =====  (or -----)
    if (/^=+\s*$/.test(next) || (/^-{3,}\s*$/.test(next) && ln.trim() && !/^\s*-\s/.test(ln))) {
      flushList(); flushPara();
      out.push('<div class="t-h4 agree-h">' + inline(ln.trim()) + '</div>');
      i++; continue;
    }
    if (/^#{1,4}\s+/.test(ln)) { flushList(); flushPara(); out.push('<div class="t-h4 agree-h">' + inline(ln.replace(/^#{1,4}\s+/, '').trim()) + '</div>'); continue; }
    // list items: "-   text" ; continuations begin with ">" or leading spaces
    const li = ln.match(/^\s*-\s+(.*)$/);
    if (li) { flushPara(); if (!list) list = []; list.push(li[1].replace(/^>\s?/, '')); continue; }
    if (list && /^\s*(>\s?|\s{2,})(.*\S)/.test(ln)) { list[list.length - 1] += ' ' + ln.replace(/^\s*(>\s?|\s+)/, '').trim(); continue; }
    if (!ln.trim()) { flushList(); flushPara(); continue; }
    if (list) { flushList(); }
    para.push(ln.replace(/^>\s?/, '').trim());
  }
  flushList(); flushPara();
  return out.join('');
}

const parts = DOCS.map(d => {
  const md = fs.readFileSync(path.join(SRC, d.file), 'utf8');
  const html = mdToHtml(md);
  return '  ' + d.key + ': ' + JSON.stringify({ title: d.title, version: d.version, html }, null, 0);
});

const banner = '/* GENERATED by tools/build-agreements.js — do not hand-edit.\n' +
  '   Source: docs/agreements/*.md · Rerun: node tools/build-agreements.js */\n';
fs.writeFileSync(path.join(ROOT, 'agreements.js'),
  banner + 'window.AGREEMENTS = {\n' + parts.join(',\n') + '\n};\n');
console.log('agreements.js written (' + DOCS.map(d => d.key).join(', ') + ')');
