/* ════════ The Labs mini-CMS renderer ════════
   Reads {events,library,labs}/data.js and emits one real page per item
   (events/{slug}/index.html …), a directory index per type, and sitemap.xml.
   Idempotent: overwrites in place and removes orphaned generated pages
   (identified by the GENERATED marker — hand-written files are never touched).

   Run:  node tools/generate.js        (then commit data.js + generated pages together)

   Production mapping (docs/OLOS_BACKEND_CHANGES.md §8): these routes are the
   static twins of /events/[slug], /library/[slug], /labs/[slug] — the slug is
   the URL contract; this script plays the part of the server renderer. */
