/* ── Teaser cards (the "card = metadata" contract; same shape as index.html's) ── */
function eventTeaser(rel, e){
  return '<a class="card tappable" href="'+rel+'events/'+e.slug+'/">'+mediaHTML(rel,e,e.kind||(e.location_type==='virtual'?'Virtual':'In person'))
    +'<div class="card-body"><div class="lbl lbl-teal">'+fmtDate(e.start_at)+'</div><div class="t-h4" style="margin:6px 0 4px;">'+esc(e.name)+'</div><p class="t-small">'+esc(e.location_name)+'</p></div></a>';
}
function resourceTeaser(rel, r){
  const typeLabel={guide:'Guide',recording:'Recording',template:'Template',course:'Course',playbook:'Playbook'}[r.content_type]||'Guide';
  return '<a class="card tappable" href="'+rel+'library/'+r.slug+'/">'+mediaHTML(rel,r,typeLabel)
    +'<div class="card-body"><div class="lbl lbl-teal">'+esc(r.meta||'')+'</div><div class="t-h4" style="margin:6px 0 4px;">'+esc(r.title)+'</div><p class="t-small">'+esc(r.summary||'')+'</p></div></a>';
}
function labTeaser(rel, m){
  const pill=m.status==='active'?'<span class="status active">Active</span>':'<span class="status forming">Waitlist open</span>';
  const sub=m.status==='active'?esc(m.partner)+' · '+m.members+' members':m.waiting+(m.waiting===1?' person':' people')+' waiting';
  return '<a class="card tappable" href="'+rel+'labs/'+m.slug+'/">'+mediaHTML(rel,m,m.slug==='dc'?'Flagship':'')
    +'<div class="card-body"><div class="card-row" style="margin-bottom:6px;">'+pill+'</div><div class="t-h4" style="margin-bottom:4px;">'+esc(m.name+(m.st&&m.slug!=='dc'?', '+m.st:''))+'</div><p class="t-small">'+sub+'</p></div></a>';
}
function relatedHTML(rel, title, teasers){
  if(!teasers.length) return '';
  // The landing's section-head component — eyebrow + rule — so recirculation reads as the same system.
  return '<section class="section"><div class="container"><div class="section-head"><div><div class="lbl lbl-teal" style="margin-bottom:8px;">More like this</div><h2 class="t-h3">'+esc(title)+'</h2></div></div><div class="cards dense">'+teasers.join('')+'</div></div></section>';
}

