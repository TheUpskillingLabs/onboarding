function emitType(dir, pages){ // pages: Map<slug|'', html>  ('' = the directory index)
  const abs=path.join(ROOT,dir);
  fs.mkdirSync(abs,{recursive:true});
  // Orphan sweep: generated entity dirs + any stray generated flat .html files
  for(const entry of fs.readdirSync(abs,{withFileTypes:true})){
    const p=path.join(abs,entry.name);
    if(entry.isDirectory()){
      const idx=path.join(p,'index.html');
      if(fs.existsSync(idx)&&fs.readFileSync(idx,'utf8').includes(MARK)&&!pages.has(entry.name)){ fs.rmSync(p,{recursive:true}); console.log('  – removed orphan '+dir+'/'+entry.name+'/'); }
    } else if(entry.name.endsWith('.html')&&entry.name!=='index.html'){
      if(fs.readFileSync(p,'utf8').includes(MARK)){ fs.unlinkSync(p); console.log('  – removed orphan '+dir+'/'+entry.name); }
    }
  }
  for(const [slug,html] of pages){
    if(slug===''){ fs.writeFileSync(path.join(abs,'index.html'),html); continue; }
    fs.mkdirSync(path.join(abs,slug),{recursive:true});
    fs.writeFileSync(path.join(abs,slug,'index.html'),html);
  }
  console.log('✓ '+dir+': '+pages.size+' pages');
}
function assertUniqueSlugs(items,label){
  const seen=new Set();
  for(const it of items){ if(!it.slug) throw new Error(label+' item missing slug: '+(it.name||it.title||it.id));
    if(seen.has(it.slug)) throw new Error('duplicate '+label+' slug: '+it.slug); seen.add(it.slug); }
}
