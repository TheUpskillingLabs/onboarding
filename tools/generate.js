const esc = s => String(s||'').replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const MO = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
function fmtDate(iso){ const d=new Date(iso); let h=d.getHours(); const ap=h>=12?'PM':'AM'; h=h%12||12; return MO[d.getMonth()]+' '+d.getDate()+' · '+h+' '+ap; }
function fmtDay(iso){ const d=new Date(iso); return ['Sunday','Monday','Tuesday','Wednesday','Thursday','Friday','Saturday'][d.getDay()]+', '+MO[d.getMonth()]+' '+d.getDate(); }
function fmtTime(iso){ const d=new Date(iso); let h=d.getHours(); const m=d.getMinutes(); const ap=h>=12?'PM':'AM'; h=h%12||12; return h+(m?':'+String(m).padStart(2,'0'):'')+' '+ap; }

